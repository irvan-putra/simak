#!/usr/bin/env python3
"""Generate the app's schedule data and the web site's data from schedule.json.

schedule.json at the repo root is the single source of truth. This script
writes:
  app/src/main/java/com/vanipy/simak/ScheduleData.java  (Java literals)
  docs/data.js                                          (window.SIMAK_DATA)
  docs/sw.js                                            (cache name stamped
                                                         from event.version so
                                                         every release busts
                                                         old offline caches)

Both are checked into the repo. --check regenerates into a temp dir and
fails if the committed files differ, so CI can prove they came from this
script and nobody edited only one side.
"""
import json
import re
import os
import shutil
import sys
import tempfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

JAVA_OUT = os.path.join(ROOT, "app/src/main/java/com/vanipy/simak/ScheduleData.java")
JS_OUT = os.path.join(ROOT, "docs/data.js")


def java_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def java_source(data):
    lines = []
    a = lines.append
    a("package com.vanipy.simak;")
    a("")
    a("/**")
    a(" * GENERATED by tools/make_data.py from schedule.json - do not edit by hand.")
    a(" * Edit schedule.json and re-run the generator instead.")
    a(" */")
    a("public final class ScheduleData {")
    a("    private ScheduleData() {}")
    a("")
    a("    public static final class Session {")
    a("        public final String id, day, date, start, end, title, speaker, kind;")
    a("        Session(String id, String day, String date, String start, String end,")
    a("                String title, String speaker, String kind) {")
    a("            this.id = id; this.day = day; this.date = date; this.start = start;")
    a("            this.end = end; this.title = title; this.speaker = speaker; this.kind = kind;")
    a("        }")
    a("    }")
    a("")
    a("    public static final class Section {")
    a("        public final String title;")
    a("        public final String[] bullets;")
    a("        Section(String title, String[] bullets) { this.title = title; this.bullets = bullets; }")
    a("    }")
    a("")
    a("    public static final String EVENT_NAME = %s;" % java_str(data["event"]["name"]))
    a("    public static final String EVENT_LONG = %s;" % java_str(data["event"]["long_name"]))
    a("    public static final String VENUE = %s;" % java_str(data["event"]["venue"]))
    a("    public static final String DATES = %s;" % java_str(data["event"]["dates"]))
    a("    public static final String SOURCE = %s;" % java_str(data["event"]["source"]))
    a("    public static final String CHECKED = %s;" % java_str(data["event"]["checked"]))
    a("    public static final String EVENT_NOTE = %s;" % java_str(data["event"]["note"]))
    a("    public static final String ABOUT = %s;" % java_str(data["guide"]["about"]))
    a("")
    a("    public static final Session[] SESSIONS = new Session[] {")
    for day in data["days"]:
        for s in day["sessions"]:
            a("        new Session(%s, %s, %s, %s, %s, %s, %s, %s)," % (
                java_str(s["id"]), java_str(day["id"]), java_str(day["date"]),
                java_str(s["start"]), java_str(s["end"]), java_str(s["title"]),
                java_str(s["speaker"]), java_str(s["kind"])))
    a("    };")
    a("")
    a("    public static final Section[] GUIDE = new Section[] {")
    for sec in data["guide"]["sections"]:
        a("        new Section(%s, new String[] {" % java_str(sec["title"]))
        for b in sec["bullets"]:
            a("            %s," % java_str(b))
        a("        }),")
    a("    };")
    a("")
    a("    /**")
    a("     * Individual speaker names inside a raw session speaker field. Org or")
    a("     * role suffixes in parentheses are dropped first, then the remainder")
    a("     * is split on \";\" for multi-speaker cards. Stripping first keeps")
    a("     * punctuation inside an affiliation like \"(A; B)\" from turning into")
    a("     * fake speaker names.")
    a("     */")
    a("    public static java.util.List<String> speakerParts(String speakerField) {")
    a("        String names = speakerField.replaceAll(\"\\\\([^()]*\\\\)\", \" \");")
    a("        java.util.List<String> out = new java.util.ArrayList<>();")
    a("        for (String part : names.split(\";\")) {")
    a("            String name = part.trim();")
    a("            if (!name.isEmpty()) out.add(name);")
    a("        }")
    a("        return out;")
    a("    }")
    a("")
    a("    /** Distinct speaker names across all sessions, for the contacts check. */")
    a("    public static String[] speakers() {")
    a("        java.util.LinkedHashSet<String> out = new java.util.LinkedHashSet<>();")
    a("        for (Session s : SESSIONS) {")
    a("            if (s.speaker.isEmpty()) continue;")
    a("            out.addAll(speakerParts(s.speaker));")
    a("        }")
    a("        return out.toArray(new String[0]);")
    a("    }")
    a("}")
    a("")
    return "\n".join(lines)


def js_source(data):
    payload = json.dumps(data, ensure_ascii=False, indent=2)
    return ("// GENERATED by tools/make_data.py from schedule.json - do not edit by hand.\n"
            "window.SIMAK_DATA = " + payload + ";\n")


SW_OUT = os.path.join(ROOT, "docs/sw.js")


def sw_source(data, template):
    """Stamp the offline cache name from event.version. Every version bump
    renames the cache, so a new service worker install pre-caches fresh
    assets and activation deletes the old cache - existing phones pick the
    update up on their next visit, without touching localStorage."""
    version = data["event"]["version"]
    stamped, n = re.subn(r"var CACHE = '[^']*';",
                         "var CACHE = 'simak-v" + version + "';",
                         template)
    if n != 1:
        raise SystemExit("docs/sw.js: expected exactly one CACHE line to stamp")
    return stamped


def write_all(root):
    with open(os.path.join(root, "schedule.json"), encoding="utf-8") as fh:
        data = json.load(fh)
    java = java_source(data)
    js = js_source(data)
    java_out = JAVA_OUT if root == ROOT else os.path.join(root, "ScheduleData.java")
    js_out = JS_OUT if root == ROOT else os.path.join(root, "data.js")
    with open(java_out, "w", encoding="utf-8") as fh:
        fh.write(java)
    with open(js_out, "w", encoding="utf-8") as fh:
        fh.write(js)
    if root == ROOT:
        with open(SW_OUT, encoding="utf-8") as fh:
            stamped = sw_source(data, fh.read())
        with open(SW_OUT, "w", encoding="utf-8") as fh:
            fh.write(stamped)


def check():
    tmp = tempfile.mkdtemp(prefix="simak-data-")
    try:
        shutil.copy(os.path.join(ROOT, "schedule.json"), os.path.join(tmp, "schedule.json"))
        write_all(tmp)
        for generated, committed in (
            (os.path.join(tmp, "ScheduleData.java"), JAVA_OUT),
            (os.path.join(tmp, "data.js"), JS_OUT),
        ):
            if not os.path.exists(committed) or open(committed, "rb").read() != open(generated, "rb").read():
                sys.exit("committed file differs from generator output: " + committed)
        with open(os.path.join(ROOT, "schedule.json"), encoding="utf-8") as fh:
            data = json.load(fh)
        with open(SW_OUT, encoding="utf-8") as fh:
            sw_committed = fh.read()
        if sw_source(data, sw_committed) != sw_committed:
            sys.exit("docs/sw.js cache name does not match event.version; run tools/make_data.py")
        print("committed data files match the generator")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


if __name__ == "__main__":
    if "--check" in sys.argv[1:]:
        check()
    else:
        write_all(ROOT)
        print("wrote ScheduleData.java, docs/data.js and stamped docs/sw.js")
